"""Rates read from tagged match events: how often shots become goals, points are won.

Decision 0007. A sport module names its analyses (`events.analyses` in
packages/shared/sports/<sport>.json): which event types are the attempts, which count as a
success, and how many attempts a player needs before their own rate is shown. Football's
"finishing" is shots that became goals; table tennis's "points" is points won. Each is broken
down by the details coaches add to their tags (where in the goal, technique, situation, the
keeper's distance; the stroke).

The rules are the platform's:

- Only players whose analytics consent is in effect are counted. A rate is analytics.
- A player is named only to a caller who may open them (`access.may_view`). The others are
  counted in every rate, as a percentile on the profile counts everyone, but not identified.
- A rate from fewer than `MIN_FOR_A_RATE` attempts is not shown; its counts are. "2 of 3" is a
  count, not a finding.
- The group is named, with how many players and attempts are in it.
- How many tags were generated by the synthetic data rather than made by a coach is said, with
  the number. Generated tags carry no tagger (data/pipelines/synthetic/tagged_events.py); their
  rates show how the generator was written, not how anyone finishes.
"""

from __future__ import annotations

import uuid
from collections import defaultdict
from datetime import date

from sqlalchemy import select
from sqlalchemy.orm import Session

from app import sports
from app.models.enums import ConsentPurpose, PlayerStatus
from app.models.match_event import MatchEvent
from app.models.player import Player
from app.services.access import Caller, consent_subquery, may_view, visible_players
from app.services.cohort import MIN_COHORT, age_label, age_years, percentile_of
from app.services.radar import GROUP_WORDS, _role

GROUPS = tuple(GROUP_WORDS)
# Below this many attempts a rate is not shown, only its counts.
MIN_FOR_A_RATE = 10
LEADERS = 10


class AnalysisError(ValueError):
    """A request the analysis cannot answer, with a message fit for the screen."""


def _rate(successes: int, attempts: int) -> float | None:
    return round(successes / attempts, 3) if attempts >= MIN_FOR_A_RATE else None


def analyse(
    db: Session,
    caller: Caller,
    *,
    sport: str,
    key: str,
    gender: str | None = None,
    group: str | None = None,
    age_from: int | None = None,
    age_to: int | None = None,
    player_id: uuid.UUID | None = None,
    today: date | None = None,
) -> dict:
    today = today or date.today()
    module = sports.registry().get(sport)
    analysis = module.analyses.get(key) if module else None
    if analysis is None:
        raise AnalysisError(f"No analysis called {key!r} for {sport!r}.")
    gender = gender or module.genders[0]
    if gender not in module.genders:
        raise AnalysisError(f"{module.label} on NorthStar does not register {gender} players.")
    if sport != "football" or group == "all":
        group = None
    if group is not None and group not in GROUPS:
        raise AnalysisError(f"No position group called {group!r}.")
    if age_from is not None and age_to is not None and age_from > age_to:
        raise AnalysisError("The youngest age is above the oldest.")

    rows = db.execute(
        select(MatchEvent, Player)
        .join(Player, Player.id == MatchEvent.player_id)
        .where(MatchEvent.sport == sport)
        .where(MatchEvent.event_type.in_(analysis.events))
        .where(Player.sex == gender)
        .where(Player.status != PlayerStatus.MERGED.value)
        .where(Player.id.in_(consent_subquery(ConsentPurpose.ANALYTICS.value, today)))
    ).all()

    def fits(player: Player) -> bool:
        if group is not None and _role(sport, player.position) != group:
            return False
        age = age_years(player.date_of_birth, today)
        if age_from is not None and (age is None or int(age) < age_from):
            return False
        if age_to is not None and (age is None or int(age) > age_to):
            return False
        return True

    events = [(e, p) for e, p in rows if fits(p)]
    players = {p.id: p for _, p in events}
    success = [analysis.is_success(e.event_type, e.outcome) for e, _ in events]

    # Every detail of the analysis's event types, once, in module order. A detail recorded only
    # for some outcomes (where in the goal: goals and saves) is read among those.
    details = {}
    for kind_key in analysis.events:
        for detail in module.events[kind_key].details.values():
            details.setdefault(detail.key, detail)
    breakdown = []
    for detail in details.values():
        counts = {value: [0, 0] for value in detail.values}
        recorded = 0
        for (event, _), won in zip(events, success):
            value = (event.details or {}).get(detail.key)
            if value in counts:
                recorded += 1
                counts[value][0] += 1
                counts[value][1] += won
        kinds = module.events
        among = (
            " or ".join(
                kinds[k].outcomes[o].label.lower()
                for k in analysis.events for o in detail.outcomes if o in kinds[k].outcomes
            )
            if detail.outcomes else None
        )
        breakdown.append({
            "key": detail.key,
            "label": detail.label,
            "grid": list(detail.grid) if detail.grid else None,
            "recorded": recorded,
            # Which outcomes the detail is recorded for, in words, when not all of them.
            "among": among,
            "values": [
                {
                    "key": value,
                    "label": detail.values[value],
                    "attempts": n,
                    "successes": s,
                    "rate": _rate(s, n),
                }
                for value, (n, s) in counts.items()
            ],
        })

    # Each player's own rate, for the leaders and the focus player.
    per_player: dict[uuid.UUID, list[int]] = defaultdict(lambda: [0, 0])
    for (_, player), won in zip(events, success):
        per_player[player.id][0] += 1
        per_player[player.id][1] += won
    qualifying = {
        pid: (s / n) for pid, (n, s) in per_player.items() if n >= analysis.min_attempts
    }

    visible = {
        p.id for p in db.execute(
            visible_players(caller).where(Player.id.in_(list(qualifying)))
        ).scalars()
    } if qualifying else set()
    ranked = sorted(qualifying, key=lambda pid: (-qualifying[pid], -per_player[pid][0]))
    leaders = []
    for pid in ranked:
        if pid in visible and may_view(db, caller, players[pid])[0]:
            n, s = per_player[pid]
            leaders.append({
                "player_id": pid,
                "full_name": players[pid].full_name,
                "position": players[pid].position,
                "age_label": age_label(players[pid].date_of_birth, today),
                "attempts": n,
                "successes": s,
                "rate": round(s / n, 3),
            })
            if len(leaders) == LEADERS:
                break

    focus = None
    if player_id is not None and player_id in players:
        player = players[player_id]
        if may_view(db, caller, player)[0]:
            n, s = per_player[player_id]
            others = sorted(qualifying.values())
            focus = {
                "player_id": player_id,
                "full_name": player.full_name,
                "attempts": n,
                "successes": s,
                "rate": round(s / n, 3) if n >= analysis.min_attempts else None,
                "percentile": (
                    percentile_of(others, qualifying[player_id])
                    if player_id in qualifying and len(others) >= MIN_COHORT else None
                ),
            }

    generated = sum(1 for event, _ in events if event.tagged_by is None)
    attempts, successes = len(events), sum(success)
    return {
        "sport": sport,
        "key": key,
        "label": analysis.label,
        "rate_label": analysis.rate_label,
        "min_attempts": analysis.min_attempts,
        "min_for_a_rate": MIN_FOR_A_RATE,
        "gender": gender,
        "group": group,
        "age_from": age_from,
        "age_to": age_to,
        "genders": list(module.genders),
        "groups": list(GROUPS) if sport == "football" else [],
        "population": _population(gender, group, age_from, age_to, len(players), attempts),
        "attempts": attempts,
        "successes": successes,
        "rate": _rate(successes, attempts),
        "breakdown": breakdown,
        "leaders": leaders,
        "qualifying": len(qualifying),
        "player": focus,
        "generated": generated,
        "note": _note(generated, attempts),
    }


def _population(gender, group, age_from, age_to, players: int, attempts: int) -> str:
    who = {"male": "men and boys", "female": "women and girls"}[gender]
    if age_from is not None and age_to is not None:
        ages = f"aged {age_from}" if age_from == age_to else f"aged {age_from} to {age_to}"
    elif age_from is not None:
        ages = f"aged {age_from} and over"
    elif age_to is not None:
        ages = f"aged {age_to} and under"
    else:
        ages = "of every age"
    role = f"{GROUP_WORDS[group]}, " if group else ""
    return f"{role}{who} {ages}: {players} players, {attempts} tagged"


def _note(generated: int, attempts: int) -> str:
    if attempts == 0:
        return "Nothing tagged in this group yet."
    if generated == attempts:
        return (
            "Every tag here was made by the synthetic data generator, not by a coach. These rates "
            "show how it was written, not how anyone finishes."
        )
    if generated:
        return (
            f"{generated} of these {attempts} tags were made by the synthetic data generator, not "
            "by a coach; the rates mix the two."
        )
    return "Tagged by coaches from match video. A tag is a person's reading of the video."
