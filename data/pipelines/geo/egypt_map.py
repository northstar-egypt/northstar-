"""Cut Egypt's 27 governorates out of Natural Earth admin-1 boundaries and write simplified SVG
paths for the web app's map (apps/web/components/egypt-map-data.ts).

Natural Earth is public domain (naturalearthdata.com). The input is the 1:10m "Admin 1, states
and provinces" layer as GeoJSON, about 40 MB, which is not kept in the repo. Download it, then:

    python data/pipelines/geo/egypt_map.py <admin1.geojson> apps/web/components/egypt-map-data.ts

The projection is equirectangular at 26.8 degrees north, which keeps Egypt's shapes in proportion
at this size. Each ring is simplified with Douglas-Peucker. The output is for showing coverage on
a screen, not for measuring distances.
"""

from __future__ import annotations

import json
import math
import sys

LAT0 = math.radians(26.8)
WIDTH = 600.0
TOLERANCE = 0.6  # in output pixels


def _polygons(geometry: dict) -> list:
    return [geometry["coordinates"]] if geometry["type"] == "Polygon" else geometry["coordinates"]


def _simplify(points: list[tuple[float, float]], tolerance: float) -> list[tuple[float, float]]:
    """Douglas-Peucker on an open line."""
    if len(points) < 3:
        return points
    (x1, y1), (x2, y2) = points[0], points[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = math.hypot(dx, dy) or 1e-9
    best, index = 0.0, 0
    for i in range(1, len(points) - 1):
        px, py = points[i]
        d = abs(dy * px - dx * py + x2 * y1 - y2 * x1) / norm
        if d > best:
            best, index = d, i
    if best <= tolerance:
        return [points[0], points[-1]]
    return _simplify(points[: index + 1], tolerance)[:-1] + _simplify(points[index:], tolerance)


def build(features: list[dict]) -> tuple[str, dict[str, dict[str, str]]]:
    lons = [lon for f in features for poly in _polygons(f["geometry"]) for ring in poly for lon, _ in ring]
    lats = [lat for f in features for poly in _polygons(f["geometry"]) for ring in poly for _, lat in ring]
    minx, maxx = min(lons) * math.cos(LAT0), max(lons) * math.cos(LAT0)
    maxy = max(lats)
    scale = WIDTH / (maxx - minx)
    height = (maxy - min(lats)) * scale

    def project(lon: float, lat: float) -> tuple[float, float]:
        return ((lon * math.cos(LAT0) - minx) * scale, (maxy - lat) * scale)

    shapes = {}
    for f in features:
        props = f["properties"]
        parts = []
        for poly in _polygons(f["geometry"]):
            for ring in poly:
                full = [project(lon, lat) for lon, lat in ring]
                # A closed ring starts and ends on one point, which collapses Douglas-Peucker to
                # nothing: simplify the two halves separately.
                half = len(full) // 2
                pts = _simplify(full[: half + 1], TOLERANCE)[:-1] + _simplify(full[half:], TOLERANCE)
                if len(pts) < 4:
                    continue
                parts.append("M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in pts) + "Z")
        shapes[props["iso_3166_2"]] = {"name": props.get("name_en") or props["name"], "d": "".join(parts)}
    return f"0 0 {WIDTH:.0f} {height:.0f}", shapes


def render(viewbox: str, shapes: dict[str, dict[str, str]]) -> str:
    lines = [
        "/**",
        " * Egypt's 27 governorates as SVG paths, keyed by ISO 3166-2:EG code (the codes app/regions.py",
        " * and the oversight API use). Generated from Natural Earth admin-1 boundaries (public domain,",
        " * naturalearthdata.com), projected equirectangularly at 26.8 degrees north and simplified for a",
        " * screen. A map for showing coverage, not for measuring distances.",
        " *",
        " * Generated by data/pipelines/geo/egypt_map.py. Do not edit by hand.",
        " */",
        "",
        f'export const EGYPT_VIEWBOX = "{viewbox}";',
        "",
        "export const GOVERNORATE_PATHS: Record<string, { name: string; d: string }> = {",
    ]
    for code in sorted(shapes):
        name = json.dumps(shapes[code]["name"], ensure_ascii=False)
        lines.append(f"  {json.dumps(code)}: {{ name: {name}, d: {json.dumps(shapes[code]['d'])} }},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main(src: str, out: str) -> None:
    with open(src, encoding="utf-8") as fh:
        data = json.load(fh)
    features = [f for f in data["features"] if f["properties"].get("adm0_a3") == "EGY"]
    viewbox, shapes = build(features)
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render(viewbox, shapes))
    print(f"{len(shapes)} governorates, viewBox {viewbox}, {sum(len(s['d']) for s in shapes.values())} bytes of paths")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
